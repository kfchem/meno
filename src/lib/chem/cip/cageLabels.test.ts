const say = (r: CipResult) => ("label" in r ? r.label + (r.turns ? "!" : "") : "no:" + r.why);
const row = (smiles: string): string => {
  const r = cipLabels(cipInput(smiles));
  const part = (m: Map<number, CipResult>, k: string) => [...m].sort((a, b) => a[0] - b[0]).map(([i, v]) => `${k}${i}:${say(v)}`).join(" ");
  return [part(r.centres, "c"), part(r.bonds, "b"), part(r.axes, "a"), part(r.cumulated, "u")].join(" | ");
};

